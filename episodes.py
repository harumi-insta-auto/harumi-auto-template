#!/usr/bin/env python3
"""投稿本文に書いてよい「実際に起きたこと」の一覧。

★このファイルは何のためにあるか

  AIに「具体的な情景や数字を1つは入れて」と頼み、同時に「失敗も正直に書いて」と
  頼むと、**AIは自分が知らないはずの過去を書きます。**「先週こんな不具合があって」
  「1週間くらい気づきませんでした」——記録を開くと、そんな週はどこにもありません。

  エラーは出ません。ワークフローは成功のまま終わります。しかも文章としては
  むしろ上手に書けているので、毎日読んでいても気づきません。

  対処は「具体を書くな」と禁じることではありません。禁止と「具体を入れろ」が
  ぶつかると、AIは**作るほう**に倒れます。効くのは逆で、
  **書いてよい具体を、先に渡してしまうことです。**

  ここに並べた出来事だけが、投稿文で触れてよい過去になります。

★ここも書き換える場所です。
  下の REAL_EPISODES に、あなたのアカウントで**実際に起きたこと**を並べます。

  - **実際に起きたことだけ。** コミットの履歴、実行ログ、APIが返した値、
    もらったDMやコメント——**記録で裏が取れるものに限ります。**
    「たぶんこうだった」は入れないでください。ここに無い出来事は
    「起きなかったこと」ではなく「**裏が取れないこと**」です。
  - `when` は実際の日付（"YYYY-MM-DD"）。
  - `what` は、投稿文にそのまま近い形で書ける平易な日本語で。
  - `keys` は「この出来事の話をしている」と機械的に見分けるための語です
    （content_generator.py の創作ガードが、過去形＋不具合語の組み合わせを
    見つけたときに、この語があれば「一覧から選んで書いた」とみなして通します）。
  - 他人の名前やアカウント名は入れないでください。

  ⚠️ **埋めないうちは、空のままで大丈夫です。** 下の例は `when` が "YYYY-MM-DD" の
     ままなので、**AIに渡す一覧からは自動的に外れます**（`real_episodes()` が
     はじきます）。日付を実際の日付に書き換えた項目から、順に有効になります。
     一覧が空の間、AIには「過去の出来事にはいっさい触れないでください」と伝わります。

     ここを空のまま運用しても、投稿は普通に出ます。**過去の話をしなくなるだけです。**
"""
from __future__ import annotations

# 実際に起きたこと。投稿文で過去の出来事に触れるときは、ここから1つだけ選ばせる。
#
# ↓ 2件は「書き方の例」です。日付を実際の日付に変えると、その項目が有効になります。
#   例のまま置いておいても害はありません（AIには渡りません）。
REAL_EPISODES: list[dict] = [
    {
        "when": "YYYY-MM-DD",
        "what": "（例）自動投稿の本番稼働を始めた。以来、毎日決まった時刻に、"
                "私が何もしなくても投稿が出ている。",
        "keys": ["稼働", "始めた日", "動き始め"],
    },
    {
        "when": "YYYY-MM-DD",
        "what": "（例）投稿画像が見切れていると、見てくれている方から指摘をもらった。"
                "画像を正方形で作っていたが、Instagram の表示枠は縦長なので"
                "左右がはみ出して切れていた。縦長（1080×1350）に作り直して直した。",
        "keys": ["見切れ", "はみ出", "正方形", "縦長"],
    },
]

# 「まだ書き換えていない項目」の目印。ここに当たる項目はAIに渡さない。
_PLACEHOLDER_MARKS = ("YYYY", "MM-DD", "（例）", "(例)")


def _is_placeholder(episode: dict) -> bool:
    """まだ書き換えていない雛形の項目なら True。

    ★ここが効かないと、あなたのアカウントでは起きていない「例」の出来事を、
      AIが実話として投稿に書きます。このファイルが防ごうとしているもの、
      そのものです。例を消さずに置いておけるのは、この関数があるからです。
    """
    text = f"{episode.get('when', '')}{episode.get('what', '')}"
    return any(mark in text for mark in _PLACEHOLDER_MARKS)


def real_episodes() -> list[dict]:
    """雛形の項目を除いた、実際に起きたことだけの一覧。"""
    return [e for e in REAL_EPISODES if not _is_placeholder(e)]


# 創作ガードの除外判定に使う語（この語が同じ文にあれば、実在の出来事の話とみなす）。
# 一覧が空のうちは空のまま＝除外なし。まだ「実在の出来事」が1つも無いのだから、
# 過去形＋不具合語の文はすべて創作の疑いでよい、という意味になります。
EPISODE_KEYS: list[str] = [k for e in real_episodes() for k in e["keys"]]


def episodes_prompt_block() -> str:
    """プロンプトに差し込む【実際に起きたこと】の一覧。空なら空文字を返す。"""
    episodes = real_episodes()
    if not episodes:
        return ""
    return "\n".join(f"　・{e['when']}：{e['what']}" for e in episodes) + "\n"


def render_markdown() -> str:
    """一覧を人が読む形（Markdown）で書き出す。

        python episodes.py > docs/実際に起きたこと.md
    """
    episodes = real_episodes()
    out = [
        "# 実際に起きたこと（投稿文に書いてよい過去の出来事）",
        "",
        "> ⚠️ **このファイルは自動生成**。正は `episodes.py` の `REAL_EPISODES`。",
        "> 直すときは `episodes.py` を編集してから作り直す：",
        "> ```bash",
        "> python episodes.py > docs/実際に起きたこと.md",
        "> ```",
        "",
        "投稿本文で**過去の出来事に触れるときは、ここにあるものだけ**を使う。",
        "ここに無い出来事・日付・期間・数値は書かせない。",
        "",
    ]
    if not episodes:
        out += [
            "（まだ1件もありません。`episodes.py` の `REAL_EPISODES` は雛形のままです。",
            "この状態では、AIは過去の出来事にいっさい触れずに書きます。）",
            "",
        ]
    for e in episodes:
        out += [f"## {e['when']}", "", e["what"], "",
                f"見分けの語：{' / '.join(e['keys'])}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    print(render_markdown())
